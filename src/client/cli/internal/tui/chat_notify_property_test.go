// Turn notifications cross a trust boundary: session names, replies and errors
// come from the daemon and end up inside an OSC 777 string that a terminal
// parses and hands to a notification server. These properties check the emitted
// sequence against docs/turn-notifications.md with oracles written here, so a
// change to the production helpers cannot quietly redefine what they promise.

// notifyCase is one generated notification: a session name, a reply, an error
// and the signoff they belong to.
type notifyCase struct {
	name  string
	reply string
	err   string
	end   HistoryEntry
	mode  notifyMode
}

// nastyPool holds the runes a payload has to survive: separators, markup,
// escapes, controls and wide or combining text.
var nastyPool = []rune("abZ09 \t\n\r;&<>\"'\\#*+-`_~|:,!?/é世👨\u200d\u0301\u202e\u00a0\x1b\x07\x00\u009b\u007f")

// genString builds a string from generated bytes, at most limit runes long.
func genString(b []byte, limit int) string {
	var sb strings.Builder
	for i, v := range b {
		if i >= limit {
			break
		}
		sb.WriteRune(nastyPool[int(v)%len(nastyPool)])
	}
	return sb.String()
}

// notificationFor builds the model a notification is made from: a history that
// ends with the signoff, the way the live paths leave it.
func notificationFor(t *testing.T, c notifyCase) string {
	t.Helper()
	m := activityChat(t)
	m.notifyMode = c.mode
	m.notifyTitle = func() string { return c.name }
	m.History.Append(HistoryEntry{Kind: EntryUser, Speaker: "You", Text: "go"})
	if c.reply != "" {
		m.History.Append(HistoryEntry{Kind: EntryAssistant, Text: c.reply})
	}
	if c.err != "" && c.end.Mood == moodFailed {
		m.History.Append(HistoryEntry{Kind: EntryError, Text: c.err})
	}
	m.History.Append(c.end)
	return m.turnNotification(c.end)
}

// notificationFields splits an OSC 777 sequence into its fields on its own,
// reporting false when the payload does not carry exactly two.
func notificationFields(t *testing.T, seq string) (title, body string, ok bool) {
	t.Helper()
	const prefix = "\x1b]777;notify;"
	if !strings.HasPrefix(seq, prefix) {
		t.Fatalf("missing OSC 777 prefix: %q", seq)
	}
	if !strings.HasSuffix(seq, "\x1b\\\a") {
		t.Fatalf("missing string terminator and bell: %q", seq)
	}
	parts := strings.Split(strings.TrimSuffix(strings.TrimPrefix(seq, prefix), "\x1b\\\a"), ";")
	if len(parts) != 2 {
		return "", "", false
	}
	return parts[0], parts[1], true
}

// payloadControl reports the runes a terminal would act on inside an escape,
// other than the space a folded line becomes.
func payloadControl(r rune) bool {
	return r < 0x20 || r == 0x7f || r >= 0x80 && r <= 0x9f
}

// TestPropTurnNotificationWellFormed checks that generated content cannot end
// the escape sequence early, split it into extra fields, or carry a control
// rune into the payload.
func TestPropTurnNotificationWellFormed(t *testing.T) {
	gen := func(b []byte) bool {
		if len(b) == 0 {
			return true
		}
		c := notifyCase{
			name:  genString(b, 60),
			reply: genString(b[len(b)/2:], 120),
			err:   genString(b[len(b)/3:], 120),
			end: HistoryEntry{
				Kind: EntryTurnEnd, ElapsedMs: int64(len(b)) * 1000, Tools: len(b) % 4,
				Mood: []mood{moodDone, moodFailed, moodStopped}[len(b)%3],
			},
			mode: notifyMode(len(b) % 2),
		}
		seq := notificationFor(t, c)

		payload := strings.TrimSuffix(strings.TrimPrefix(seq, "\x1b]777;notify;"), "\x1b\\\a")
		for _, r := range payload {
			if payloadControl(r) {
				t.Logf("control rune %q in %q (name=%q reply=%q err=%q)", r, seq, c.name, c.reply, c.err)
				return false
			}
		}
		// Markup characters become lookalikes, so the payload carries none.
		if strings.ContainsAny(payload, "&<>") {
			t.Logf("raw markup in %q (name=%q reply=%q err=%q)", seq, c.name, c.reply, c.err)
			return false
		}
		// Whatever the content, the payload is exactly a title and a body.
		title, body, ok := notificationFields(t, seq)
		if !ok || title == "" || body == "" || strings.Count(payload, ";") != 1 {
			t.Logf("fields=%q (name=%q reply=%q err=%q)", seq, c.name, c.reply, c.err)
			return false
		}
		return true
	}
	if err := quick.Check(gen, &quick.Config{MaxCount: 2000, Rand: rand.New(rand.NewSource(1))}); err != nil {
		t.Fatal(err)
	}
}

// foldText is the documented one-line form: whitespace runs become one space
// and the line is trimmed.
func foldText(text string) string {
	return strings.Join(strings.Fields(text), " ")
}

// markupFree applies the documented preview rules: no inline emphasis and no
// code marks.
func markupFree(line string) string {
	return strings.NewReplacer("**", "", "__", "", "`", "").Replace(line)
}

// elapsedText is the documented duration form, written out so the oracle does
// not reach into the production formatter.
func elapsedText(ms int64) string {
	s := ms / 1000
	switch {
	case s < 60:
		return strconv.FormatInt(s, 10) + "s"
	case s < 3600:
		return fmt.Sprintf("%dm %ds", s/60, s%60)
	}
	return fmt.Sprintf("%dh %dm", s/3600, s/60%60)
}

// TestPropTurnNotificationContent checks the documented title and body for
// content that needs no escaping: the fields must carry it verbatim, cut to the
// documented cell limits, and nothing else.
func TestPropTurnNotificationContent(t *testing.T) {
	const plain = "abcdefghijklmnopqrstuvwxyz ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:!?/+-_()[]{}'\"=#@$%^|~"
	gen := func(b []byte) bool {
		var sb strings.Builder
		for _, v := range b {
			sb.WriteByte(plain[int(v)%len(plain)])
		}
		name := strings.TrimSpace(sb.String())
		if name == "" || len(b) == 0 {
			return true
		}
		c := notifyCase{
			name:  name,
			reply: sb.String(),
			end:   HistoryEntry{Kind: EntryTurnEnd, Mood: moodDone, ElapsedMs: int64(len(b)) * 1000},
			mode:  notifyOn,
		}
		title, body, ok := notificationFields(t, notificationFor(t, c))
		if !ok {
			return false
		}
		if want := "albedo · " + ansi.Truncate(foldText(name), notifyTitleLimit, "…"); title != want {
			t.Logf("title=%q want %q", title, want)
			return false
		}
		preview := ansi.Truncate(foldText(markupFree(strings.TrimLeft(c.reply, "#>*-+ "))), notifyPreviewLimit, "…")
		want := "Done in " + elapsedText(c.end.ElapsedMs)
		if preview != "" {
			want += " — " + preview
		}
		if body != want {
			t.Logf("body=%q want %q (name=%q reply=%q)", body, want, name, c.reply)
			return false
		}
		return true
	}
	if err := quick.Check(gen, &quick.Config{MaxCount: 1000, Rand: rand.New(rand.NewSource(3))}); err != nil {
		t.Fatal(err)
	}
}

// TestPropNotifyTextLimits checks that a field is cut to its cell budget on a
// character boundary and never keeps an escape sequence.
func TestPropNotifyTextLimits(t *testing.T) {
	gen := func(b []byte) bool {
		if len(b) == 0 {
			return true
		}
		text := strings.Repeat(genString(b, 40), 8)
		got := notifyText(text, notifyPreviewLimit)
		// Markup characters are written as one-cell lookalikes, so the field
		// keeps its cell budget as shown.
		shown := strings.NewReplacer("\uff06", "&", "\u2039", "<", "\u203a", ">").Replace(got)
		if w := ansi.StringWidth(shown); w > notifyPreviewLimit {
			t.Logf("width %d over limit for %q", w, text)
			return false
		}
		if strings.ContainsAny(got, "\x1b\x07") {
			t.Logf("escape survived: %q", got)
			return false
		}
		cut := strings.TrimSuffix(shown, "…")
		folded := foldText(strings.Map(func(r rune) rune {
			if payloadControl(r) {
				return ' '
			}
			return r
		}, text))
		// Nothing is invented: every rune of the field comes from the text,
		// with the separator written as a comma.
		present := map[rune]bool{}
		for _, r := range folded {
			present[r] = true
		}
		present[','] = true
		for _, r := range cut {
			if !present[r] {
				t.Logf("field %q has %q, absent from %q", got, r, folded)
				return false
			}
		}
		for _, r := range cut {
			if payloadControl(r) {
				t.Logf("control rune %q in %q", r, got)
				return false
			}
		}
		return true
	}
	if err := quick.Check(gen, &quick.Config{MaxCount: 500, Rand: rand.New(rand.NewSource(5))}); err != nil {
		t.Fatal(err)
	}
}

// drainRaws collects what tea.Raw writes from cmd without waiting on the
// commands that block, such as ticks and reads.
func drainRaws(cmd tea.Cmd) []string {
	if cmd == nil {
		return nil
	}
	raws := make(chan string, 64)
	var walk func(tea.Cmd)
	walk = func(c tea.Cmd) {
		if c == nil {
			return
		}
		go func() {
			defer func() { _ = recover() }()
			switch msg := c().(type) {
			case tea.BatchMsg:
				for _, child := range msg {
					walk(child)
				}
			case tea.RawMsg:
				if s, ok := msg.Msg.(string); ok {
					raws <- s
				}
			}
		}()
	}
	walk(cmd)
	quiet := time.NewTimer(3 * time.Millisecond)
	defer quiet.Stop()
	var out []string
	for {
		select {
		case s := <-raws:
			out = append(out, s)
			quiet.Reset(3 * time.Millisecond)
		case <-quiet.C:
			return out
		}
	}
}

// notifyModel is an independent model of the notification rule: a live turn's
// signoff notifies once, while the model is blurred, in a mode that notifies,
// and only for a turn that lasted at least the documented minimum.
type notifyModel struct {
	clock    int64
	open     bool
	start    int64
	last     int64
	answered bool
	tools    int
	failed   bool
	blurred  bool
	quiet    bool
}

// ending returns what the model expects when the open turn ends.
func (n *notifyModel) ending(failed, stopped bool) int {
	if !n.open {
		return 0
	}
	n.open = false
	if !n.answered && n.tools == 0 && !failed && !stopped {
		return 0
	}
	// The documentation's minimum, not the production constant, so a change to
	// the threshold shows up as a failure.
	const minimumMs = 10_000
	if !n.blurred || n.quiet || n.last-n.start < minimumMs {
		return 0
	}
	return 1
}

// TestPropTurnNotificationOnce checks the delivery rule over generated
// interleavings of turns, endings, focus changes and status reads: each live
// signoff notifies exactly once and nothing else notifies.
func TestPropTurnNotificationOnce(t *testing.T) {
	gen := func(script []byte) bool {
		if len(script) == 0 {
			return true
		}
		t.Setenv("TMUX", "")
		m := activityChat(t)
		m.notifyMode = notifyOn
		m.notifyTitle = func() string { return "s" }
		m.focus(false)
		// The model times a turn from its own event clock, which the harness
		// stamps onto every event, not from the wall clock the test runs on.
		// Events carry timestamps on the test's own base so the turn clock the
		// model keeps and the one the events carry agree.
		base := time.Now().UnixMilli()
		model := notifyModel{clock: 1_000_000, blurred: true}
		for step, b := range script {
			model.clock += int64(b%5) * 7000
			at := base + model.clock - 1_000_000
			expect := 0
			var cmd tea.Cmd
			stream := func(evt daemon.StreamEvent) tea.Cmd {
				m, cmd = m.Update(ChatStreamEventMsg{SessionID: m.SessionID, Generation: m.Generation, Event: evt})
				return cmd
			}
			switch int(b) % 13 {
			case 0: // a person's message opens a turn, closing one in flight silently
				if model.open {
					model.ending(false, false)
					expect = 0
				}
				stream(daemon.StreamEvent{Type: daemon.EventUser, EntryID: fmt.Sprintf("user-%d", step), Source: "chat", Text: "go", Timestamp: &at})
				model.open, model.start, model.last, model.answered, model.tools, model.failed = true, at, at, false, 0, false
				expect = 0
			case 1: // mail opens a turn only when none is in flight
				stream(daemon.StreamEvent{Type: daemon.EventUser, EntryID: fmt.Sprintf("mail-%d", step), Source: "mail", Text: "mail", Timestamp: &at})
				if !model.open {
					model.open, model.start, model.last, model.answered, model.tools, model.failed = true, at, at, false, 0, false
				}
			case 2: // a reply answers the turn
				stream(daemon.StreamEvent{Type: daemon.EventMessage, EntryID: fmt.Sprintf("reply-%d", step), Text: "done", Timestamp: &at})
				if !model.open {
					model.open, model.start, model.last, model.tools, model.failed = true, at, at, 0, false
				}
				model.last = at
				model.answered = true
			case 3: // a tool call
				stream(daemon.StreamEvent{Type: daemon.EventTool, EntryID: fmt.Sprintf("tool-%d", step), ToolName: "python"})
				if !model.open {
					// An unstamped event opens the turn at the client's clock.
					wall := time.Now().UnixMilli()
					model.open, model.start, model.last, model.answered, model.failed = true, wall, wall, false, false
				}
				model.tools++
			case 4: // completion
				stream(daemon.StreamEvent{Type: daemon.EventTurnCompleted})
				expect = model.ending(false, false)
			case 5: // failure
				stream(daemon.StreamEvent{Type: daemon.EventError, Text: "boom"})
				if model.open {
					model.failed = true
				}
				expect = model.ending(true, false)
			case 6: // interruption
				stream(daemon.StreamEvent{Type: daemon.EventInterrupted})
				expect = model.ending(false, true)
			case 8: // the terminal reports focus, which the app applies to the chat
				cmd = m.focus(true)
				model.blurred = false
			case 9: // the terminal reports blur
				cmd = m.focus(false)
				model.blurred = true
			case 10: // a replayed signoff describes history, not this session
				stream(daemon.StreamEvent{Type: daemon.EventTurnCompleted, Replayed: true})
				model.open = false
			case 12: // the notification mode changes between turns
				mode := []notifyMode{notifyOn, notifyBrief, notifyOff}[int(b)%3]
				m.notifyMode = mode
				model.quiet = mode == notifyOff
			case 11: // a replayed message is history too, and opens nothing live
				stream(daemon.StreamEvent{Type: daemon.EventUser, EntryID: fmt.Sprintf("replay-%d", step), Source: "chat", Text: "then", Replayed: true, Timestamp: &at})
				if model.open {
					model.ending(false, false)
				}
				model.open, model.start, model.last, model.answered, model.tools, model.failed = true, at, at, false, 0, false
			case 7: // a status read that finds the session idle; only a turn that
				// showed activity counts as begun
				if model.open && (model.tools > 0 || model.last > model.start) {
					expect = model.ending(false, false)
				}
				idle := daemon.AgentStatus{Idle: true}
				m, cmd = m.Update(ChatStatusMsg{SessionID: m.SessionID, Generation: m.Generation, Revision: m.statusRevision, Status: &idle})
			}
			got := drainRaws(cmd)
			got = append(got, drainRaws(m.takeTurnNotification())...)
			if len(got) != expect {
				t.Logf("script %v step %d op %d: %d notifications, model expected %d (%q)", script, step, int(b)%13, len(got), expect, got)
				return false
			}
			for _, seq := range got {
				if title, _, ok := notificationFields(t, seq); !ok || title != "albedo · s" {
					t.Logf("notification %q", seq)
					return false
				}
			}
		}
		return true
	}
	if err := quick.Check(gen, &quick.Config{MaxCount: 40, Rand: rand.New(rand.NewSource(7))}); err != nil {
		t.Fatal(err)
	}
}
